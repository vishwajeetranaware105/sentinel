// Drives the fix screen with real key presses against a local repo (no push: the company hook blocks unapproved remotes).
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import React from 'react';
process.env.SENTINEL_HOME = fs.mkdtempSync(path.join(os.tmpdir(), 'sent-fixui-'));
const { render } = await import('ink-testing-library');
const { FixSession } = await import('../src/fix.js');
const { FixScreen } = await import('../src/tui/fix.js');
const sh = (cwd, ...a) => execFileSync('git', a, { cwd, encoding: 'utf8' }).trim();
const root = fs.mkdtempSync(path.join(os.tmpdir(), 'sent-ui-remote-'));
const seed = path.join(root, 'seed'); fs.mkdirSync(seed); sh(seed, 'init', '-q', '-b', 'master'); sh(seed, 'config', 'user.email', 'a@b.c'); sh(seed, 'config', 'user.name', 'a');
fs.writeFileSync(path.join(seed, 'app.js'), 'function total(a, b) {\n  return a + b;\n}\n'); sh(seed, 'add', '-A'); sh(seed, 'commit', '-qm', 'init'); sh(seed, 'checkout', '-qb', 'feature'); fs.appendFileSync(path.join(seed, 'app.js'), '// f\n'); sh(seed, 'commit', '-qam', 'f');
fs.mkdirSync(path.join(root, 'AX')); sh(root, 'clone', '-q', '--bare', seed, path.join(root, 'AX', 'demo.git'));
const cfg = { bitbucket: { username: 'me', token: '' }, llm: { model: 'm' }, cloneUrlTemplate: path.join(root, '{ws}', '{repo}.git') };
const bb = { discussion: async () => [{ id: 1, path: 'app.js', line: 2, resolved: false, messages: [{ id: 1, who: 'Rev', slug: 'rev', email: 'r@x.com', text: 'Coerce to numbers please', at: 1 }] }] };
const llm = { json: async () => ({ action: 'edit', edits: [{ file: 'app.js', find: '  return a + b;', replace: '  return Number(a) + Number(b);' }], summary: 'Coerce operands to numbers', reply: 'done' }) };
const session = new FixSession({ cfg, bb, llm, pr: { workspace: 'AX', repository: 'demo', id: 3, title: 'My PR', source_branch: 'feature', destination_branch: 'master' } });
const r = render(React.createElement(FixScreen, { session, dims: { w: 110, h: 30 }, onBack() {} }));
const text = () => r.lastFrame().replace(/\x1b\[[0-9;]*m/g, '');
const until = async (re, ms = 6000) => { const t0 = Date.now(); while (Date.now() - t0 < ms) { if (re.test(text())) return true; await new Promise((x) => setTimeout(x, 80)); } return false; };
let fails = 0; const ok = (c, m) => { console.log(c ? 'PASS' : 'FAIL', m); if (!c) { fails++; console.log(text()); } };
ok(await until(/Coerce to numbers please/), 'lists the open comment with its text');
r.stdin.write('\r');
ok(await until(/Coerce operands to numbers/), 'shows what was changed after Enter');
ok(/\+\s+return Number\(a\)/.test(text()), 'shows the diff');
r.stdin.write('c');
ok(await until(/Committed as [0-9a-f]{8}\. Nothing is pushed yet/), 'commit needs a key press and says nothing is pushed');
r.stdin.write('p');
ok(await until(/Push to feature on Bitbucket\? y\/N/), 'push asks for confirmation first');
r.stdin.write('n');
ok(await until(/Press p to push/) && sh(path.join(process.env.SENTINEL_HOME, 'fix/AX/demo/pr-3'), 'rev-list', '--count', 'HEAD') === '3', 'declining leaves the commit local');
r.unmount(); process.exit(fails ? 1 : 0);
